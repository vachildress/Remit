"""Adapter from remit grants to the Microsoft Agent Governance Toolkit (AGT).

remit decides; AGT enforces. On every call the adapter recomputes the
envelope from the ledger, translates it and the tool table into an AGT
``PolicyDocument`` (one rule per tool), and lets AGT's ``PolicyEvaluator``
make the decision. The adapter does not intercept calls itself: it
implements AGT's ``ToolCallInterceptor`` protocol, so AGT's framework
integrations call ``intercept`` in front of the agent's tools.

Where AGT's interfaces forced a compromise:

* AGT policy actions are allow, deny, audit and block; there is no hold. A
  held tool is written as a deny rule named ``remit:hold:<tool>``, and the
  adapter files the call in AGT's human approval queue
  (``EscalationHandler``) and reports it as held.
* AGT conditions compare one context field with a value. They cannot
  express evidence, time or grant logic, so the policy is regenerated from
  the envelope on every call and matches only on ``tool_name``.
* ``ToolCallResult`` has only ``allowed``; hold and deny are both
  ``allowed=False``, told apart by ``audit_entry["remit_decision"]``.
* AGT's default action when no rule matches is allow. The adapter sets the
  document default to deny, so unknown tools fail closed.
"""

from __future__ import annotations

from datetime import datetime
from typing import Any, Callable, Mapping

from agent_os.integrations.base import ToolCallRequest, ToolCallResult
from agent_os.integrations.escalation import EscalationHandler
from agent_os.policies import (
    PolicyAction,
    PolicyCondition,
    PolicyDefaults,
    PolicyDocument,
    PolicyEvaluator,
    PolicyOperator,
    PolicyRule,
)

from ..evidence.ledger import Ledger
from ..evidence.model import Capability, Level, Subject, utcnow
from ..evidence.requirements import RuleSet
from ..policy.evaluator import Envelope
from ..policy.history import refresh
from .decision import ALLOW, DENY, HOLD, Decision, decide
from .tools import ToolTable

RULE_PREFIX = "remit"
RED_LINE_PRIORITY = 1000
TOOL_PRIORITY = 100


def to_agt_policy(envelope: Envelope, table: ToolTable) -> PolicyDocument:
    """Translate an envelope and the tool table into an AGT policy document."""
    rules = []
    for tool, reason in table.red_lines.items():
        rules.append(
            PolicyRule(
                name=f"{RULE_PREFIX}:red_line:{tool}",
                condition=PolicyCondition(field="tool_name", operator=PolicyOperator.EQ, value=tool),
                action=PolicyAction.DENY,
                priority=RED_LINE_PRIORITY,
                message=decide(envelope, table, tool).explanation,
            )
        )
    for tool in table.tools:
        d = decide(envelope, table, tool)
        rules.append(
            PolicyRule(
                name=f"{RULE_PREFIX}:{d.outcome}:{tool}",
                condition=PolicyCondition(field="tool_name", operator=PolicyOperator.EQ, value=tool),
                action=PolicyAction.ALLOW if d.outcome == ALLOW else PolicyAction.DENY,
                priority=TOOL_PRIORITY,
                message=d.explanation,
            )
        )
    return PolicyDocument(
        name=f"{RULE_PREFIX}:{envelope.subject}",
        description=f"Generated by remit from the envelope as of {envelope.as_of.isoformat()}",
        rules=rules,
        defaults=PolicyDefaults(action=PolicyAction.DENY),
    )


class AGTAdapter:
    """A remit PEP backed by AGT's policy evaluator and approval queue."""

    name = "agt"

    def __init__(
        self,
        ledger: Ledger,
        rules: RuleSet,
        table: ToolTable,
        escalations: EscalationHandler | None = None,
        parent_levels: Mapping[Capability, Level] | None = None,
        clock: Callable[[], datetime] = utcnow,
    ) -> None:
        self.ledger = ledger
        self.rules = rules
        self.table = table
        self.escalations = escalations or EscalationHandler()
        self.parent_levels = parent_levels
        # AGT's ToolCallRequest carries no time, so intercept asks the clock.
        self.clock = clock

    def check(self, subject: Subject, tool: str, now: datetime | None = None) -> Decision:
        envelope = refresh(self.ledger, self.rules, subject, now or self.clock(), self.parent_levels)
        policy = to_agt_policy(envelope, self.table)
        result = PolicyEvaluator(policies=[policy]).evaluate({"tool_name": tool, "agent_id": str(subject)})
        ours = decide(envelope, self.table, tool)
        outcome = _outcome(result.matched_rule, result.allowed)
        escalation_id = None
        if outcome == HOLD:
            request = self.escalations.escalate(
                agent_id=str(subject),
                action=tool,
                reason=result.reason,
                context_snapshot={"capability": ours.capability.value if ours.capability else None},
            )
            escalation_id = request.request_id
        return Decision(
            **{
                **ours.__dict__,
                # AGT's evaluation is what is enforced; its reason is our explanation.
                "outcome": outcome,
                "explanation": result.reason if result.matched_rule else ours.explanation,
                "escalation_id": escalation_id,
                "enforced_by": self.name,
            }
        )

    def intercept(self, request: ToolCallRequest) -> ToolCallResult:
        """AGT ``ToolCallInterceptor`` entry point. ``agent_id`` must be ``agent@version``."""
        try:
            subject = Subject.parse(request.agent_id)
        except ValueError as exc:
            return ToolCallResult(allowed=False, reason=f"remit: {exc}", audit_entry={"remit_decision": DENY})
        d = self.check(subject, request.tool_name)
        audit: dict[str, Any] = {
            "remit_decision": d.outcome,
            "remit_binding": d.binding,
            "capability": d.capability.value if d.capability else None,
            "required": d.required.value if d.required else None,
            "granted": d.granted.value if d.granted else None,
            "escalation_id": d.escalation_id,
        }
        return ToolCallResult(allowed=d.outcome == ALLOW, reason=d.explanation, audit_entry=audit)


def _outcome(matched_rule: str | None, allowed: bool) -> str:
    if matched_rule and matched_rule.startswith(f"{RULE_PREFIX}:{HOLD}:"):
        return HOLD
    return ALLOW if allowed else DENY
